"""
HemoSmart - Outreach Policy Sensitivity Sweep
-------------------------------------------------
The donor-outreach policy trades shortages against wastage, mostly for
platelets (5-day shelf life):
  - a longer outreach window anticipates demand spikes (fewer shortages)
    but collects units that expire before they're needed (more waste);
  - a higher alert cap closes big gaps faster but contacts more donors.

This sweeps both knobs for the full HemoSmart policy over the same
simulated worlds as evaluation/simulate.py, and picks a default with an
explicit rule: minimise  cost = SHORTAGE_WEIGHT x units short + units
wasted, where a unit is "wasted" if it expired OR was shipped out (so
redistribution can't hide over-collection). A shortage is weighted
higher because an unmet transfusion harms a patient; a wasted unit
costs a donation.

Run (from the repo root):
    python -m evaluation.sensitivity            # 90 days, 3 seeds

Writes evaluation/results/sensitivity.md and sensitivity.json.
"""

import argparse
import json
import os
from datetime import datetime

import evaluation.simulate as sim  # sets up the throwaway database first
from agents.autonomy.agents import DonorAgent
from bloodbank.catalog import OUTREACH_WINDOW_DAYS

SHORTAGE_WEIGHT = 3
PLATELET_WINDOWS = (2, 3, 4, 5, 6, 7)
ALERT_CAPS = (8, 16)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--days", type=int, default=90)
    parser.add_argument("--seeds", type=int, default=3)
    args = parser.parse_args()

    start = sim.DEFAULT_START
    seeds = list(range(1, args.seeds + 1))
    worlds = {s: sim.build_world(start, args.days, s) for s in seeds}
    original = (OUTREACH_WINDOW_DAYS["Platelets"], DonorAgent.MAX_ALERTS_PER_SHORTAGE)

    rows = []
    try:
        for window in PLATELET_WINDOWS:
            for cap in ALERT_CAPS:
                OUTREACH_WINDOW_DAYS["Platelets"] = window
                DonorAgent.MAX_ALERTS_PER_SHORTAGE = cap
                runs = [sim.run_policy("hemosmart", worlds[s], start, args.days, s) for s in seeds]
                mean = lambda key: sum(r[key] for r in runs) / len(runs)  # noqa: E731
                row = {
                    "platelet_window_days": window,
                    "alert_cap": cap,
                    "shortage_units": round(mean("shortage_units"), 1),
                    "platelet_shortage": round(sum(r["shortage_by_component"]["Platelets"] for r in runs) / len(runs), 1),
                    "expired": round(mean("expired"), 1),
                    "transferred": round(mean("transferred"), 1),
                    "not_used_here": round(mean("not_used_here"), 1),
                    "donor_alerts": round(mean("donor_alerts"), 1),
                }
                row["cost"] = round(SHORTAGE_WEIGHT * row["shortage_units"] + row["not_used_here"], 1)
                rows.append(row)
                print(row, flush=True)
    finally:
        OUTREACH_WINDOW_DAYS["Platelets"], DonorAgent.MAX_ALERTS_PER_SHORTAGE = original

    best = min(rows, key=lambda r: r["cost"])
    meta = {"days": args.days, "seeds": seeds, "start": str(start.date()), "shortage_weight": SHORTAGE_WEIGHT,
            "generated_at": datetime.now().strftime("%Y-%m-%d %H:%M")}
    os.makedirs(sim.RESULTS_DIR, exist_ok=True)
    with open(os.path.join(sim.RESULTS_DIR, "sensitivity.json"), "w") as f:
        json.dump({"meta": meta, "rows": rows, "best": best}, f, indent=2)

    lines = [
        "# HemoSmart — Outreach Policy Sensitivity",
        "",
        f"Full HemoSmart policy, {args.days} days from {meta['start']}, mean of seeds {seeds}. "
        f"cost = {SHORTAGE_WEIGHT} × units short + units not used here (expired + redistributed). "
        f"Generated by `python -m evaluation.sensitivity` on {meta['generated_at']}.",
        "",
        "| Platelet window (days) | Alert cap | Units short | of which platelets | Expired | Redistributed | Not used here | Donor alerts | Cost |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        mark = " **← lowest cost**" if r is best else ""
        lines.append(
            f"| {r['platelet_window_days']} | {r['alert_cap']} | {r['shortage_units']} | {r['platelet_shortage']} | "
            f"{r['expired']} | {r['transferred']} | {r['not_used_here']} | {r['donor_alerts']} | {r['cost']}{mark} |"
        )
    with open(os.path.join(sim.RESULTS_DIR, "sensitivity.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nBest: {best}\nWrote {sim.RESULTS_DIR}/sensitivity.md")


if __name__ == "__main__":
    main()
